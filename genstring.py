import asyncio
import getpass
import os
BOT_NAME = (os.environ.get('BOT_NAME') or 'Music Bot').strip()
from pyrogram import Client as c
API_ID = input('\nEnter Your API_ID:\n > ')
API_HASH = getpass.getpass('\nEnter Your API_HASH (hidden):\n > ')
print('\n\n Enter Phone number when asked.\n\n')
i = c(':memory:', api_id=API_ID, api_hash=API_HASH)

async def main():
    await i.start()
    ss = await i.export_session_string()
    xx = f"HERE IS YOUR STRING SESSION, COPY IT, DON'T SHARE!!\n\n`{ss}`\n\nGENERATED BY {BOT_NAME}"
    await i.send_message('me', xx)
    print("\nHERE IS YOUR STRING SESSION, COPY IT, DON'T SHARE!!\n")
    print(f'\n{ss}\n')
    print(f'\nGENERATED BY {BOT_NAME}\n')
asyncio.run(main())
